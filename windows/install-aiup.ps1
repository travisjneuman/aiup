# close the PowerShell window.
if ($MyInvocation.MyCommand.CommandType -eq 'ExternalScript' -and
    [string]$MyInvocation.MyCommand.ScriptContents -match 'function Invoke-AiupInstaller') {
    exit $aiupExitCode
}
$global:LASTEXITCODE = $aiupExitCode
