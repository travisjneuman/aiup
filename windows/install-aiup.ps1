# aiup installer for Windows (Windows PowerShell 5.1 and PowerShell 7).
#
#   irm https://raw.githubusercontent.com/travisjneuman/aiup/main/windows/install-aiup.ps1 | iex
#
# Options, when saved to a file or run as a script block:
#   & ([scriptblock]::Create((irm https://raw.githubusercontent.com/travisjneuman/aiup/main/windows/install-aiup.ps1))) -Uninstall
#   powershell -NoProfile -ExecutionPolicy Bypass -File install-aiup.ps1 [-Uninstall] [-AllUsers]
#
#   -Uninstall  remove the aiup commands, the launcher and the PATH entry
#   -AllUsers   install under Program Files and use the machine PATH. Needs an
#               elevated terminal. The installer never elevates itself.
#
# Environment:
#   AIUP_PYTHON=C:\path\to\python.exe   use this Python (3.9 or newer)
#   AIUP_NO_MODIFY_PATH=1               leave PATH alone
#
# Nothing runs from a script file during "irm | iex", so this works under the
# default Restricted execution policy. This file must stay plain ASCII.

param(
    [switch]$Uninstall,
    [switch]$AllUsers
)

function Invoke-AiupInstaller {
    param([bool]$Uninstall, [bool]$AllUsers)

    Set-StrictMode -Version 2.0
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'

    $LauncherUrl = 'https://raw.githubusercontent.com/travisjneuman/aiup/main/runtime/launcher/aiup_launcher.py'
    if ($env:AIUP_LAUNCHER_URL) { $LauncherUrl = $env:AIUP_LAUNCHER_URL }
    $MaxBytes = 1048576
    $ShimMarker = 'aiup shim (generated by install-aiup.ps1)'
    # Official winget source ids. Python.Python.3.14 offers user and machine
    # scope installers that put py.exe and python.exe on PATH.
    $PythonWingetId = 'Python.Python.3.14'
    $FzfWingetId = 'junegunn.fzf'
    $MachineEnvKey = 'SYSTEM\CurrentControlSet\Control\Session Manager\Environment'
    $Stamp = Get-Date -Format 'yyyyMMdd-HHmmss'

    function Say([string]$Text) { Write-Host $Text }
    function Warn([string]$Text) { [Console]::Error.WriteLine('aiup installer: ' + $Text) }
    function Fail([string]$Text) { throw (New-Object System.Exception ('aiup installer: ' + $Text)) }

    function Test-Interactive {
        try {
            return ([Environment]::UserInteractive -and -not [Console]::IsInputRedirected)
        } catch {
            return $false
        }
    }

    function Confirm-Step([string]$Question) {
        if (-not (Test-Interactive)) { return $false }
        $answer = Read-Host ($Question + ' [y/N]')
        return ([string]$answer -match '^(y|yes)$')
    }

    function Test-Elevated {
        $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
        $principal = New-Object Security.Principal.WindowsPrincipal $identity
        return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    }

    # Run a program with captured output and a time limit. Returns $null when
    # it could not start or ran too long.
    function Invoke-Captured([string]$FilePath, [string]$Arguments, [int]$TimeoutMs, [switch]$DefaultPolicy) {
        $info = New-Object System.Diagnostics.ProcessStartInfo
        $info.FileName = $FilePath
        $info.Arguments = $Arguments
        $info.UseShellExecute = $false
        $info.RedirectStandardInput = $true
        $info.RedirectStandardOutput = $true
        $info.RedirectStandardError = $true
        $info.CreateNoWindow = $true
        $info.StandardOutputEncoding = New-Object System.Text.UTF8Encoding $false
        $info.StandardErrorEncoding = New-Object System.Text.UTF8Encoding $false
        if ($DefaultPolicy) {
            # A -ExecutionPolicy given to this session is passed to children
            # through this variable. Drop it to see the real policy.
            [void]$info.EnvironmentVariables.Remove('PSExecutionPolicyPreference')
        }
        $process = New-Object System.Diagnostics.Process
        $process.StartInfo = $info
        try {
            [void]$process.Start()
        } catch {
            $process.Dispose()
            return $null
        }
        try {
            $process.StandardInput.Close()
            $stdout = $process.StandardOutput.ReadToEndAsync()
            $stderr = $process.StandardError.ReadToEndAsync()
            if (-not $process.WaitForExit($TimeoutMs)) {
                try { $process.Kill() } catch { }
                return $null
            }
            $process.WaitForExit()
            # A program it started may still hold the pipe open. Do not wait on it forever.
            if (-not $stdout.Wait(5000)) { return $null }
            [void]$stderr.Wait(1000)
            return New-Object PSObject -Property @{ ExitCode = $process.ExitCode; Output = [string]$stdout.Result }
        } finally {
            $process.Dispose()
        }
    }

    # --- PATH helpers ---------------------------------------------------------

    function ConvertTo-PathKey([string]$Entry) {
        $value = [Environment]::ExpandEnvironmentVariables($Entry.Trim().Trim('"')).TrimEnd('\', '/')
        return $value.ToLowerInvariant()
    }

    function Open-EnvironmentKey([bool]$Machine, [bool]$Writable) {
        if ($Machine) {
            return [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey($MachineEnvKey, $Writable)
        }
        return [Microsoft.Win32.Registry]::CurrentUser.OpenSubKey('Environment', $Writable)
    }

    function Get-RegistryPath([bool]$Machine) {
        $key = Open-EnvironmentKey $Machine $false
        if ($null -eq $key) { return '' }
        try {
            return [string]$key.GetValue('Path', '')
        } finally {
            $key.Close()
        }
    }

    # Pick up PATH entries that installers (winget, Python) just added.
    function Update-SessionPath {
        $seen = @{}
        $parts = New-Object System.Collections.ArrayList
        foreach ($entry in ([string]$env:Path -split ';')) {
            if (-not $entry) { continue }
            $seen[(ConvertTo-PathKey $entry)] = $true
            [void]$parts.Add($entry)
        }
        $changed = $false
        foreach ($entry in (((Get-RegistryPath $true) + ';' + (Get-RegistryPath $false)) -split ';')) {
            if (-not $entry) { continue }
            $key = ConvertTo-PathKey $entry
            if ($seen.ContainsKey($key)) { continue }
            $seen[$key] = $true
            [void]$parts.Add($entry)
            $changed = $true
        }
        if ($changed) { $env:Path = ($parts.ToArray() -join ';') }
    }

    function Add-SessionPath([string]$Dir) {
        $want = ConvertTo-PathKey $Dir
        foreach ($entry in ([string]$env:Path -split ';')) {
            if ($entry -and (ConvertTo-PathKey $entry) -eq $want) { return }
        }
        $env:Path = $Dir + ';' + $env:Path
    }

    function Remove-SessionPath([string]$Dir) {
        $want = ConvertTo-PathKey $Dir
        $kept = @([string]$env:Path -split ';' | Where-Object { $_ -and (ConvertTo-PathKey $_) -ne $want })
        $env:Path = ($kept -join ';')
    }

    # Used only when the launcher cannot run during uninstall. Keeps the value
    # type (REG_SZ or REG_EXPAND_SZ) and every other entry as written.
    function Remove-RegistryPathEntry([string]$Dir, [bool]$Machine) {
        $key = Open-EnvironmentKey $Machine $true
        if ($null -eq $key) { return }
        try {
            $raw = $key.GetValue('Path', '', [Microsoft.Win32.RegistryValueOptions]::DoNotExpandEnvironmentNames)
            if (-not $raw) { return }
            $kind = $key.GetValueKind('Path')
            $want = ConvertTo-PathKey $Dir
            $kept = @(([string]$raw) -split ';' | Where-Object { (-not $_) -or ((ConvertTo-PathKey $_) -ne $want) })
            $new = $kept -join ';'
            if ($new -ne [string]$raw) {
                $key.SetValue('Path', $new, $kind)
                Say ('Removed ' + $Dir + ' from PATH. Open a new terminal to see the change.')
            }
        } finally {
            $key.Close()
        }
    }

    # --- Python ---------------------------------------------------------------

    # Returns the absolute python.exe for a candidate that runs Python 3.9 or
    # newer, or $null. Store alias stubs fail to run and are skipped. A Store
    # Python is skipped too: its writes under AppData are redirected into the
    # app's private folder, which would hide aiup's state.
    function Get-PythonPath([string]$Exe, [string]$Prefix) {
        if (-not $Exe -or -not (Test-Path -LiteralPath $Exe -PathType Leaf)) { return $null }
        $code = 'import sys; print(sys.version_info[:2] >= (3, 9)); print(sys.executable)'
        $result = Invoke-Captured $Exe ($Prefix + '-I -X utf8 -c "' + $code + '"') 10000
        if ($null -eq $result -or $result.ExitCode -ne 0) { return $null }
        $lines = @($result.Output -split "`r?`n" | Where-Object { $_ -ne '' })
        if ($lines.Count -lt 2 -or $lines[0].Trim() -ne 'True') { return $null }
        $path = $lines[1].Trim()
        if (-not $path -or -not [IO.Path]::IsPathRooted($path)) { return $null }
        if ($path -match '\\WindowsApps\\') { return $null }
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { return $null }
        return $path
    }

    function Find-Python {
        $candidates = New-Object System.Collections.ArrayList
        if ($env:AIUP_PYTHON) { [void]$candidates.Add(@($env:AIUP_PYTHON, '')) }
        foreach ($cmd in @(Get-Command py.exe -CommandType Application -All -ErrorAction SilentlyContinue)) {
            [void]$candidates.Add(@($cmd.Path, '-3 '))
        }
        foreach ($name in @('python.exe', 'python3.exe')) {
            foreach ($cmd in @(Get-Command $name -CommandType Application -All -ErrorAction SilentlyContinue)) {
                [void]$candidates.Add(@($cmd.Path, ''))
            }
        }
        # Fresh installs that this session's PATH does not show yet.
        # Each root is a folder and the name pattern of the Python folders in it.
        # The Python install manager keeps its runtimes in LOCALAPPDATA\Python.
        $roots = New-Object System.Collections.ArrayList
        if ($env:LOCALAPPDATA) {
            [void]$candidates.Add(@((Join-Path $env:LOCALAPPDATA 'Programs\Python\Launcher\py.exe'), '-3 '))
            [void]$roots.Add(@((Join-Path $env:LOCALAPPDATA 'Programs\Python'), 'Python3*'))
            [void]$roots.Add(@((Join-Path $env:LOCALAPPDATA 'Python'), 'pythoncore-3*'))
        }
        if ($env:ProgramFiles) { [void]$roots.Add(@($env:ProgramFiles, 'Python3*')) }
        foreach ($pair in $roots) {
            $root = [string]$pair[0]
            if (-not (Test-Path -LiteralPath $root)) { continue }
            $found = @(Get-ChildItem -LiteralPath $root -Directory -Filter ([string]$pair[1]) -ErrorAction SilentlyContinue |
                Sort-Object { [int](($_.Name -replace '\D', '') + '0') } -Descending)
            foreach ($dir in $found) {
                [void]$candidates.Add(@((Join-Path $dir.FullName 'python.exe'), ''))
            }
        }
        $tried = @{}
        foreach ($candidate in $candidates) {
            $key = ([string]$candidate[0]).ToLowerInvariant() + '|' + $candidate[1]
            if ($tried.ContainsKey($key)) { continue }
            $tried[$key] = $true
            $path = Get-PythonPath ([string]$candidate[0]) ([string]$candidate[1])
            if ($path) { return $path }
        }
        if ($env:AIUP_PYTHON) { Warn ('AIUP_PYTHON=' + $env:AIUP_PYTHON + ' is not a usable Python 3.9 or newer.') }
        return $null
    }

    function Get-WingetCommand {
        return (Get-Command winget.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1)
    }

    # Run winget in this console with a time limit, so a winget that cannot
    # start or never answers does not stop the install. Returns its exit code,
    # or $null when it could not start or ran too long.
    function Invoke-Winget([string]$Path, [string[]]$WingetArgs, [int]$TimeoutMs) {
        try {
            $process = Start-Process -FilePath $Path -ArgumentList $WingetArgs -NoNewWindow -PassThru -ErrorAction Stop
        } catch {
            Warn ('winget could not start: ' + $_.Exception.Message)
            return $null
        }
        try {
            # Reading the handle now keeps ExitCode readable after exit in Windows PowerShell 5.1.
            [void]$process.Handle
            if (-not $process.WaitForExit($TimeoutMs)) {
                try { $process.Kill() } catch { }
                Warn ('winget did not finish within ' + [int]($TimeoutMs / 60000) + ' minutes, so it was stopped.')
                return $null
            }
            $process.WaitForExit()
            return [int]$process.ExitCode
        } finally {
            $process.Dispose()
        }
    }

    function Format-ExitCode($Code) {
        if ($null -eq $Code) { return 'no exit code' }
        return ('exit code 0x{0:X8}' -f [int]$Code)
    }

    function Install-PythonFromWinget {
        $scope = 'user'
        if ($AllUsers) { $scope = 'machine' }
        $wingetArgs = @('install', '--id', $PythonWingetId, '--exact', '--source', 'winget', '--scope', $scope,
            '--silent', '--accept-package-agreements', '--accept-source-agreements')
        $display = 'winget ' + ($wingetArgs -join ' ')
        $winget = Get-WingetCommand
        if (-not (Test-Interactive) -or -not $winget) {
            Say 'Python 3.9 or newer was not found. Install it with:'
            Say ('  ' + $display)
            if (-not $winget) { Say 'winget was not found. Python is also available from https://www.python.org/downloads/windows/' }
            return $false
        }
        if (-not (Confirm-Step 'Python 3.9 or newer was not found. Install Python from winget now?')) {
            Say 'Skipped. Install it later with:'
            Say ('  ' + $display)
            return $false
        }
        Say ('+ ' + $display)
        $code = Invoke-Winget $winget.Path $wingetArgs 900000
        if ($code -ne 0) {
            Warn ('winget did not install Python (' + (Format-ExitCode $code) + ').')
            return $false
        }
        Update-SessionPath
        return $true
    }

    function Test-Fzf {
        if (Get-Command fzf.exe -CommandType Application -ErrorAction SilentlyContinue) { return $true }
        if ($env:LOCALAPPDATA) {
            return (Test-Path -LiteralPath (Join-Path $env:LOCALAPPDATA 'Microsoft\WinGet\Links\fzf.exe'))
        }
        return $false
    }

    function Install-Fzf {
        if (Test-Fzf) { return }
        $wingetArgs = @('install', '--id', $FzfWingetId, '--exact', '--source', 'winget', '--scope', 'user',
            '--accept-package-agreements', '--accept-source-agreements')
        $display = 'winget ' + ($wingetArgs -join ' ')
        $winget = Get-WingetCommand
        Say 'fzf (used by the aiup menus) was not found. This installs it for your account:'
        Say ('  ' + $display)
        $installed = $false
        if (-not $winget) {
            Say 'winget was not found, so it was not run.'
        } elseif (-not (Test-Interactive)) {
            Say 'No terminal to ask on, so it was not run.'
        } elseif (Confirm-Step 'Run it now?') {
            Say ('+ ' + $display)
            $code = Invoke-Winget $winget.Path $wingetArgs 300000
            if ($code -eq 0) {
                $installed = $true
                Update-SessionPath
            } else {
                Warn ('winget did not install fzf (' + (Format-ExitCode $code) + ').')
            }
        }
        if (-not $installed) {
            Say 'Continuing without fzf. Install it later with that command, or with "scoop install fzf".'
        }
    }

    # --- launcher download ------------------------------------------------------

    function Get-Launcher([string]$Python, [string]$Destination) {
        if (-not $LauncherUrl.StartsWith('https://')) { Fail 'the launcher URL must use HTTPS' }
        if ($PSVersionTable.PSVersion.Major -lt 6) {
            [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor
                [Net.SecurityProtocolType]::Tls12
        }
        $dir = Split-Path -Parent $Destination
        $tmp = Join-Path $dir ('.aiup-install-' + [Guid]::NewGuid().ToString('N') + '.tmp')
        try {
            $downloaded = $false
            for ($attempt = 1; $attempt -le 3 -and -not $downloaded; $attempt++) {
                try {
                    Invoke-WebRequest -UseBasicParsing -Uri $LauncherUrl -OutFile $tmp -TimeoutSec 30
                    $downloaded = $true
                } catch {
                    if ($attempt -eq 3) { Fail ('could not download the aiup launcher: ' + $_.Exception.Message) }
                    Start-Sleep -Seconds 2
                }
            }
            $item = Get-Item -LiteralPath $tmp
            if ($item.Length -eq 0) { Fail 'the downloaded launcher was empty' }
            if ($item.Length -gt $MaxBytes) { Fail 'the downloaded launcher was larger than 1 MiB' }
            $text = [IO.File]::ReadAllText($tmp, (New-Object Text.UTF8Encoding $false))
            $first = ($text -split "`n", 2)[0].TrimEnd("`r")
            if ($first -ne '#!/usr/bin/env python3') { Fail 'the downloaded launcher had an unexpected first line' }
            foreach ($marker in @('AIUP_LAUNCHER_REVISION =', 'AIUP_RELEASE_URL', 'def validate_generation(')) {
                if (-not $text.Contains($marker)) { Fail ('the downloaded file was missing the marker ' + $marker) }
            }
            $check = 'import sys; compile(open(sys.argv[1], encoding=''utf-8'').read(), sys.argv[1], ''exec'', dont_inherit=True)'
            $result = Invoke-Captured $Python ('-I -B -X utf8 -c "' + $check + '" "' + $tmp + '"') 30000
            if ($null -eq $result -or $result.ExitCode -ne 0) { Fail 'the downloaded launcher failed the Python syntax check' }
            Move-Item -LiteralPath $tmp -Destination $Destination -Force
        } finally {
            if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
        }
    }

    # --- shims ------------------------------------------------------------------

    function Write-FileAtomic([string]$Path, [string]$Content, [Text.Encoding]$Encoding) {
        $dir = Split-Path -Parent $Path
        $tmp = Join-Path $dir ('.aiup-' + [Guid]::NewGuid().ToString('N') + '.tmp')
        try {
            [IO.File]::WriteAllText($tmp, $Content, $Encoding)
            Move-Item -LiteralPath $tmp -Destination $Path -Force
        } finally {
            if (Test-Path -LiteralPath $tmp) { Remove-Item -LiteralPath $tmp -Force -ErrorAction SilentlyContinue }
        }
    }

    function Test-OurShim([string]$Path) {
        if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return $false }
        try {
            $head = @(Get-Content -LiteralPath $Path -TotalCount 3 -ErrorAction Stop)
        } catch {
            return $false
        }
        foreach ($line in $head) {
            if ([string]$line -like ('*' + $ShimMarker + '*')) { return $true }
        }
        return $false
    }

    function Move-Aside([string]$Path) {
        if ((Test-Path -LiteralPath $Path) -and -not (Test-OurShim $Path)) {
            $backup = $Path + '.aiup-backup-' + $Stamp
            Move-Item -LiteralPath $Path -Destination $backup -Force
            Say ('Moved the existing ' + $Path + ' to ' + $backup)
        }
    }

    function Test-Ascii([string]$Text) {
        return ($Text -cmatch '^[\x20-\x7E]*$')
    }

    # cmd reads a .cmd file in the console code page, so keep it ASCII where we
    # can: a non-ASCII profile path is written through %LOCALAPPDATA% or
    # %USERPROFILE%. All-users shims keep literal paths.
    function ConvertTo-CmdPath([string]$Path) {
        if ((Test-Ascii $Path) -or $AllUsers) { return $Path }
        foreach ($name in @('LOCALAPPDATA', 'USERPROFILE')) {
            $value = [Environment]::GetEnvironmentVariable($name)
            if (-not $value) { continue }
            $value = $value.TrimEnd('\')
            if ($Path.StartsWith($value + '\', [StringComparison]::OrdinalIgnoreCase)) {
                return ('%' + $name + '%' + $Path.Substring($value.Length))
            }
        }
        return $Path
    }

    function ConvertTo-SingleQuoted([string]$Text) {
        return "'" + $Text.Replace("'", "''") + "'"
    }

    function ConvertTo-ShQuoted([string]$Text) {
        return "'" + $Text.Replace("'", "'\''") + "'"
    }

    function Test-ScriptsAllowed {
        $hosts = New-Object System.Collections.ArrayList
        $windowsPowerShell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
        if (Test-Path -LiteralPath $windowsPowerShell) { [void]$hosts.Add($windowsPowerShell) }
        foreach ($cmd in @(Get-Command pwsh.exe -CommandType Application -All -ErrorAction SilentlyContinue)) {
            if (-not $hosts.Contains($cmd.Path)) { [void]$hosts.Add($cmd.Path) }
        }
        if ($hosts.Count -eq 0) { return $false }
        foreach ($exe in $hosts) {
            $result = Invoke-Captured $exe '-NoLogo -NoProfile -NonInteractive -Command Get-ExecutionPolicy' 20000 -DefaultPolicy
            if ($null -eq $result) { return $false }
            $policy = $result.Output.Trim()
            if (@('RemoteSigned', 'Unrestricted', 'Bypass') -notcontains $policy) { return $false }
        }
        return $true
    }

    function Write-Shims([string]$BinDir, [string]$Python, [string]$Launcher) {
        foreach ($text in @($Python, $Launcher)) {
            if ($text.Contains('%') -or $text.Contains('"')) {
                Fail ('paths with % or a double quote are not supported: ' + $text)
            }
        }
        $crlf = "`r`n"

        # aiup.cmd: cmd, PowerShell (when aiup.ps1 is absent), OpenSSH sessions
        # and anything else that runs .cmd files from PATH.
        # The launcher path is written out in full: %~dp0 can name the wrong
        # folder when cmd finds a quoted command name through PATH.
        $cmdPython = ConvertTo-CmdPath $Python
        $cmdLauncher = ConvertTo-CmdPath $Launcher
        $cmdLines = @(
            '@echo off',
            ('rem ' + $ShimMarker),
            'setlocal',
            ('set "AIUP_PYTHON=' + $cmdPython + '"'),
            'if not exist "%AIUP_PYTHON%" goto aiup_missing',
            ('"%AIUP_PYTHON%" -I -B -X utf8 "' + $cmdLauncher + '" %*'),
            'exit /b %ERRORLEVEL%',
            ':aiup_missing',
            'echo aiup: Python was not found. Run the aiup installer again. 1>&2',
            'exit /b 9009'
        )
        $cmdEncoding = New-Object Text.ASCIIEncoding
        if (-not ((Test-Ascii $cmdPython) -and (Test-Ascii $cmdLauncher))) {
            Warn 'a path in aiup.cmd has characters cmd may not read correctly. PowerShell and Git Bash are not affected.'
            try {
                $cmdEncoding = [Text.Encoding]::GetEncoding([Globalization.CultureInfo]::CurrentCulture.TextInfo.OEMCodePage)
            } catch {
                $cmdEncoding = New-Object Text.UTF8Encoding $false
            }
        }
        $cmdPath = Join-Path $BinDir 'aiup.cmd'
        Move-Aside $cmdPath
        Write-FileAtomic $cmdPath (($cmdLines -join $crlf) + $crlf) $cmdEncoding

        # aiup.ps1: PowerShell picks it before aiup.cmd in the same folder, which
        # avoids cmd's "Terminate batch job (Y/N)?" after Ctrl-C. Written only
        # when every installed PowerShell may run local scripts.
        $ps1Path = Join-Path $BinDir 'aiup.ps1'
        if (Test-ScriptsAllowed) {
            $ps1Lines = @(
                ('# ' + $ShimMarker),
                ('$aiupPython = ' + (ConvertTo-SingleQuoted $Python)),
                ('$aiupLauncher = ' + (ConvertTo-SingleQuoted $Launcher)),
                'if (-not (Test-Path -LiteralPath $aiupPython -PathType Leaf)) {',
                '    [Console]::Error.WriteLine(''aiup: Python was not found. Run the aiup installer again.'')',
                '    exit 9009',
                '}',
                'if ($MyInvocation.ExpectingInput) {',
                '    $input | & $aiupPython -I -B -X utf8 $aiupLauncher @args',
                '} else {',
                '    & $aiupPython -I -B -X utf8 $aiupLauncher @args',
                '}',
                'exit $LASTEXITCODE'
            )
            Move-Aside $ps1Path
            # A BOM lets Windows PowerShell 5.1 read non-ASCII paths as UTF-8.
            Write-FileAtomic $ps1Path (($ps1Lines -join $crlf) + $crlf) (New-Object Text.UTF8Encoding $true)
        } else {
            if (Test-OurShim $ps1Path) { Remove-Item -LiteralPath $ps1Path -Force }
            Say 'PowerShell script policy blocks local scripts, so PowerShell will use aiup.cmd.'
        }

        # aiup (no extension): Git Bash and other MSYS shells, which do not run
        # .cmd files by bare name. Windows paths with forward slashes work there.
        $shLines = @(
            '#!/bin/sh',
            ('# ' + $ShimMarker),
            ('exec ' + (ConvertTo-ShQuoted ($Python.Replace('\', '/'))) + ' -I -B -X utf8 ' +
                (ConvertTo-ShQuoted ($Launcher.Replace('\', '/'))) + ' "$@"')
        )
        $shPath = Join-Path $BinDir 'aiup'
        Move-Aside $shPath
        Write-FileAtomic $shPath (($shLines -join "`n") + "`n") (New-Object Text.UTF8Encoding $false)
    }

    # --- install and uninstall --------------------------------------------------

    function Get-InstallRoot {
        if ($AllUsers) {
            if (-not $env:ProgramFiles) { Fail 'ProgramFiles is not set' }
            return (Join-Path $env:ProgramFiles 'aiup')
        }
        if (-not $env:LOCALAPPDATA -or -not [IO.Path]::IsPathRooted($env:LOCALAPPDATA)) {
            Fail 'LOCALAPPDATA is not set to an absolute path'
        }
        return (Join-Path $env:LOCALAPPDATA 'Programs\aiup')
    }

    function Invoke-SetupPath([string]$Python, [string]$Launcher, [string[]]$SetupArgs) {
        $allArgs = @('-I', '-B', '-X', 'utf8', $Launcher, 'setup-path') + $SetupArgs
        & $Python @allArgs | Out-Host
        return ($LASTEXITCODE -eq 0)
    }

    function Install-Aiup {
        if ($AllUsers -and -not (Test-Elevated)) {
            Fail '-AllUsers needs an elevated terminal (Run as administrator). The installer never elevates itself.'
        }
        if (-not $AllUsers -and (Test-Elevated)) {
            Say 'This terminal is elevated. aiup is still installed for this account only.'
        }
        $root = Get-InstallRoot
        $binDir = Join-Path $root 'bin'
        $launcherDir = Join-Path $root 'launcher'
        $launcher = Join-Path $launcherDir 'aiup_launcher.py'

        $python = Find-Python
        if (-not $python) {
            if (Install-PythonFromWinget) { $python = Find-Python }
            if (-not $python) { Fail 'aiup needs Python 3.9 or newer. Install it, then run this installer again.' }
        }
        if ($AllUsers -and $env:USERPROFILE -and $python.StartsWith($env:USERPROFILE.TrimEnd('\') + '\', [StringComparison]::OrdinalIgnoreCase)) {
            Warn ('the Python at ' + $python + ' is inside your user folder, so other accounts cannot run the shared aiup command.')
        }
        Install-Fzf

        foreach ($dir in @($binDir, $launcherDir)) {
            if (-not (Test-Path -LiteralPath $dir)) { [void](New-Item -ItemType Directory -Path $dir -Force) }
        }
        Get-Launcher $python $launcher
        Write-Shims $binDir $python $launcher

        if ($env:AIUP_NO_MODIFY_PATH -eq '1') {
            Say 'AIUP_NO_MODIFY_PATH=1 is set, so PATH was not changed. Add this folder to PATH yourself:'
            Say ('  ' + $binDir)
        } else {
            $setupArgs = @()
            if ($AllUsers) { $setupArgs += '--system' }
            $setupArgs += $binDir
            if (-not (Invoke-SetupPath $python $launcher $setupArgs)) {
                Warn ('PATH could not be updated. Add this folder to PATH yourself: ' + $binDir)
            }
        }
        Add-SessionPath $binDir
        Say ('Installed aiup in ' + $binDir + ' (Python: ' + $python + ')')
        Say 'This PowerShell window can run aiup now. Open a new terminal anywhere else; programs that were already open keep their old PATH.'
        return 0
    }

    function Remove-Aiup {
        if ($AllUsers -and -not (Test-Elevated)) {
            Fail '-AllUsers needs an elevated terminal (Run as administrator). The installer never elevates itself.'
        }
        $root = Get-InstallRoot
        $binDir = Join-Path $root 'bin'
        $launcherDir = Join-Path $root 'launcher'
        $launcher = Join-Path $launcherDir 'aiup_launcher.py'

        $pathDone = $false
        if (Test-Path -LiteralPath $launcher) {
            $python = Find-Python
            if ($python) {
                $setupArgs = @('--remove')
                if ($AllUsers) { $setupArgs += '--system' }
                $setupArgs += $binDir
                $pathDone = Invoke-SetupPath $python $launcher $setupArgs
            }
        }
        if (-not $pathDone) { Remove-RegistryPathEntry $binDir ([bool]$AllUsers) }
        Remove-SessionPath $binDir

        foreach ($name in @('aiup.cmd', 'aiup.ps1', 'aiup')) {
            $path = Join-Path $binDir $name
            if (Test-OurShim $path) {
                Remove-Item -LiteralPath $path -Force
                Say ('Removed ' + $path)
            } elseif (Test-Path -LiteralPath $path) {
                Warn ($path + ' was not made by this installer; left in place.')
            }
        }
        if (Test-Path -LiteralPath $launcher) {
            Remove-Item -LiteralPath $launcher -Force
            Say ('Removed ' + $launcher)
        }
        foreach ($dir in @($binDir, $launcherDir, $root)) {
            if ((Test-Path -LiteralPath $dir) -and -not (Get-ChildItem -LiteralPath $dir -Force | Select-Object -First 1)) {
                Remove-Item -LiteralPath $dir -Force
            }
        }

        $left = @()
        if ($env:AIUP_STATE_DIR) {
            if (Test-Path -LiteralPath $env:AIUP_STATE_DIR) { $left += $env:AIUP_STATE_DIR }
        } elseif ($env:LOCALAPPDATA) {
            foreach ($name in @('config', 'data', 'state', 'cache')) {
                $dir = Join-Path $env:LOCALAPPDATA ('aiup\' + $name)
                if (Test-Path -LiteralPath $dir) { $left += $dir }
            }
        }
        if ($left.Count -gt 0) {
            Say 'Your aiup settings, history and downloads were kept. To remove them too:'
            foreach ($dir in $left) { Say ('  Remove-Item -Recurse -Force -LiteralPath ' + (ConvertTo-SingleQuoted $dir)) }
        }
        Say 'aiup was uninstalled.'
        return 0
    }

    try {
        if ($PSVersionTable.PSVersion.Major -ge 6 -and -not $IsWindows) {
            Fail 'this installer is for Windows. On Linux use linux/install-aiup; on macOS use macos/install-aiup.'
        }
        if ($Uninstall) { return (Remove-Aiup) }
        return (Install-Aiup)
    } catch {
        $message = $_.Exception.Message
        if (-not $message.StartsWith('aiup installer:')) { $message = 'aiup installer: ' + $message }
        [Console]::Error.WriteLine($message)
        return 1
    }
}

$aiupExitCode = [int](@(Invoke-AiupInstaller -Uninstall ([bool]$Uninstall) -AllUsers ([bool]$AllUsers))[-1])
Remove-Item -Path Function:\Invoke-AiupInstaller -ErrorAction SilentlyContinue
